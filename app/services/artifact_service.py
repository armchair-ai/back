import logging
import re
from pathlib import Path
from typing import Any, Iterable, Optional

logger = logging.getLogger(__name__)

DEFAULT_BRAIN_DIR = Path("/tmp/.gemini/antigravity/brain")


class ArtifactService:
    """Service responsible for extracting, resolving, and locating artifact files
    generated by Antigravity agents across structured outputs, raw text, and filesystem."""

    def resolve_artifact_path(
        self,
        *,
        structured_output: Any = None,
        field_keys: Iterable[str] = ("filename", "summary_file"),
        response_text: Optional[str] = None,
        fallback_pattern: Optional[str] = "**/*.md",
        brain_dir: Path = DEFAULT_BRAIN_DIR,
    ) -> Optional[str]:
        """Resolves the artifact file path using a multi-strategy approach:
        1. Checks structured output fields.
        2. Inspects response text for markdown links or absolute paths.
        3. Falls back to finding the most recently modified file matching the pattern in brain directory.
        """
        # 1. Intentar obtener desde structured output
        if structured_output:
            for key in field_keys:
                val = self._extract_field(structured_output, key)
                if val and isinstance(val, str) and val.strip():
                    clean_path = val.strip()
                    if Path(clean_path).exists():
                        logger.debug(f"Resolved artifact from structured field '{key}': {clean_path}")
                        return clean_path

        # 2. Intentar extraer del texto de la respuesta (enlaces file:// o rutas absolutas)
        if response_text:
            text_match = self._find_path_in_text(response_text)
            if text_match:
                logger.debug(f"Resolved artifact from response text: {text_match}")
                return text_match

        # 3. Fallback: buscar el archivo más reciente en el directorio brain
        if fallback_pattern and brain_dir.exists():
            recent_file = self._find_latest_file(brain_dir, fallback_pattern)
            if recent_file:
                logger.debug(f"Resolved artifact from brain fallback: {recent_file}")
                return str(recent_file)

        return None

    def _extract_field(self, obj: Any, key: str) -> Any:
        if isinstance(obj, dict):
            return obj.get(key)
        return getattr(obj, key, None)

    def _find_path_in_text(self, text: str) -> Optional[str]:
        patterns = [
            r"file://([^\s\)\"']+\.md)",
            r"(/tmp/[^\s\)\"']+\.md)",
            r"(/workspace/[^\s\)\"']+\.md)",
        ]
        for pattern in patterns:
            match = re.search(pattern, text)
            if match:
                candidate = match.group(1)
                if Path(candidate).exists():
                    return candidate
        return None

    def _find_latest_file(self, base_dir: Path, pattern: str) -> Optional[Path]:
        try:
            files = list(base_dir.glob(pattern))
            if files:
                return max(files, key=lambda f: f.stat().st_mtime)
        except Exception as e:
            logger.warning(f"Error searching latest file in {base_dir} with pattern {pattern}: {e}")
        return None


artifact_service = ArtifactService()
